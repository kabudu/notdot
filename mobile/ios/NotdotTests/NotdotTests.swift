/// Pairs with a desktop simulator on the host (see mobile/README.md). Skipped
/// unless the runner passes TEST_RUNNER_NOTDOT_TEST_QR_FILE.
final class LinkEndToEndTests: XCTestCase {
    func testPairDirectThenRelayOnlyRetryCommitsOnce() async throws {
        guard let path = ProcessInfo.processInfo.environment["NOTDOT_TEST_QR_FILE"] else {
            throw XCTSkip("no desktop simulator; set TEST_RUNNER_NOTDOT_TEST_QR_FILE")
        }
        let qr = try String(contentsOfFile: path, encoding: .utf8)
        let link = PhoneLink()
        let code = try await link.pair(qr: qr, name: "Simulator phone")
        XCTAssertEqual(code.count, 7)
        guard case .approved = try await link.awaitApproval() else { return XCTFail("not approved") }
        let direct = try await link.connect(relayOnly: false)
        XCTAssertEqual(direct, .direct)
        let id = newRequestId()
        let first = try await link.addNote(requestId: id, text: "Synthetic note")
        let relayed = try await link.connect(relayOnly: true)
        XCTAssertEqual(relayed, .relay)
        let retried = try await link.addNote(requestId: id, text: "Synthetic note")
        XCTAssertEqual(first, retried, "the retry returns the recorded outcome")
        let notes = try await link.listNotes()
        XCTAssertEqual(notes.filter { $0 == "Synthetic note" }.count, 1)
    }
}
