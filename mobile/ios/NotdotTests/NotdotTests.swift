import AVFoundation
import XCTest
@testable import Notdot

private let fixtures = Bundle(for: OrbAdapterTests.self).resourceURL!.appendingPathComponent("orb-golden")

private func goldenIndex() throws -> [String: Any] {
    try JSONSerialization.jsonObject(with: Data(contentsOf: fixtures.appendingPathComponent("index.json"))) as! [String: Any]
}

/// Raw RGBA8 (premultiplied, top row first), raw DEFLATE.
private func goldenPixels(_ file: String) throws -> [UInt8] {
    let packed = try Data(contentsOf: fixtures.appendingPathComponent(file))
    return [UInt8](try (packed as NSData).decompressed(using: .zlib) as Data)
}

final class OrbAdapterTests: XCTestCase {
    func testGeneratedShadersCarryTheCanonicalFingerprint() throws {
        let hash = orbShaderSha256()
        XCTAssertEqual(hash, try goldenIndex()["shader_sha256"] as? String)
        XCTAssertTrue(orbMetalFragment().contains("orb.frag sha256=\(hash)"))
        XCTAssertTrue(orbMetalVertex().contains("orb.frag sha256=\(hash)"))
        XCTAssertEqual(orbUniformNames().count, 11)
    }

    /// Renders every golden frame through the app's Metal adapter on this
    /// device's GPU and compares with the goldens (generated by the macOS
    /// Metal path, itself identical to the canonical WebGL render).
    func testGoldenFramesMatchOnThisGPU() throws {
        let index = try goldenIndex()
        let size = try XCTUnwrap(index["size"] as? Int)
        let renderer = try OrbRenderer()
        var worst = (name: "", mean: 0.0, max: 0)
        for frame in try XCTUnwrap(index["frames"] as? [[String: Any]]) {
            let block = try XCTUnwrap(frame["block"] as? [NSNumber]).map(\.floatValue)
            let file = try XCTUnwrap(frame["file"] as? String)
            let rendered = try renderer.renderPixels(block: block, size: size)
            let golden = try goldenPixels(file)
            XCTAssertEqual(rendered.count, golden.count, file)
            var sum = 0, maxDiff = 0
            for (a, b) in zip(rendered, golden) {
                let d = abs(Int(a) - Int(b))
                sum += d
                maxDiff = max(maxDiff, d)
            }
            let mean = Double(sum) / Double(rendered.count)
            if mean > worst.mean { worst = (file, mean, maxDiff) }
            // Target from the design: mean per-channel difference <= 2/255.
            XCTAssertLessThanOrEqual(mean, 2.0, "\(file) mean \(mean) max \(maxDiff)")
        }
        print("orb golden parity: worst \(worst.name) mean \(worst.mean) max \(worst.max)")
    }

    func testEngineFramesFollowTheDesktopClock() {
        let engine = OrbEngine()
        let state = OrbState(mode: .listening, task: .none, hue: orbDefaultHue(), level: nil, reducedMotion: false,
                             quota: .normal, taskAvailable: false, microphoneMuted: false, wakeReady: true, offline: false)
        let first = engine.frame(state: state, nowMs: 0, width: 300, height: 300)
        XCTAssertEqual(first?.block.count, 16)
        XCTAssertNil(engine.frame(state: state, nowMs: 16, width: 300, height: 300), "30 fps cap")
        XCTAssertEqual(first?.accessibilityLabel, "Listening. Wake word on.")
    }
}

final class SessionLifecycleTests: XCTestCase {
    func testHandsFreeSessionThroughTheSharedCore() {
        var policy = defaultSessionPolicy(platform: .ios)
        policy.microphonePermitted = true
        let session = VoiceSession(policy: policy)
        _ = session.handle(event: .appVisible, nowMs: 0)
        let started = session.handle(event: .start(source: .app), nowMs: 0)
        XCTAssertEqual(started.state, .handsFree)
        XCTAssertTrue(started.microphone && started.surface)
        XCTAssertEqual(started.remainingMs, 600_000, "default idle timeout is ten minutes")
        let hidden = session.handle(event: .appHidden, nowMs: 1_000)
        XCTAssertTrue(hidden.microphone, "a user-started session continues when hidden")
        let call = session.handle(event: .interruptionBegan, nowMs: 2_000)
        XCTAssertEqual(call.state, .paused(reason: .interrupted))
        XCTAssertFalse(call.microphone)
        let ended = session.handle(event: .stop, nowMs: 3_000)
        XCTAssertTrue(ended.endSurface)
        XCTAssertFalse(ended.microphone)
    }
}

