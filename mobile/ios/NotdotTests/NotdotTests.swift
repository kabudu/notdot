/// The desktop's wake corpus, offline through the embedded sherpa library
/// and the bundled models. No microphone, no playback.
final class WakeCorpusTests: XCTestCase {
    private func samples(_ name: String) throws -> [Float] {
        let url = Bundle(for: Self.self).resourceURL!.appendingPathComponent("fixtures/\(name)")
        let file = try AVAudioFile(forReading: url, commonFormat: .pcmFormatFloat32, interleaved: false)
        XCTAssertEqual(file.processingFormat.sampleRate, 16_000)
        let buffer = try XCTUnwrap(AVAudioPCMBuffer(pcmFormat: file.processingFormat, frameCapacity: AVAudioFrameCount(file.length)))
        try file.read(into: buffer)
        return Array(UnsafeBufferPointer(start: buffer.floatChannelData![0], count: Int(buffer.frameLength)))
    }

    /// Feed `clip` after other speech, in 20 ms packets: faster than real
    /// time, except while a backup decode runs, when packets are paced in
    /// real time as they would arrive live. Then silence continues while a
    /// decode is still running (up to 4 s).
    private func detects(_ engine: WakeEngine, _ clip: String, _ gain: Float) throws -> Bool {
        let before = try samples("negative.wav").map { $0 * 0.3 }
        let audio = before + [Float](repeating: 0, count: 3_200) + (try samples(clip)).map { $0 * gain } + [Float](repeating: 0, count: 12_800)
        engine.reset()
        for start in stride(from: 0, to: audio.count, by: 320) {
            if engine.backupBusy() { Thread.sleep(forTimeInterval: 0.02) }
            if engine.accept(samples: Array(audio[start..<min(start + 320, audio.count)]), rate: 16_000) { return true }
        }
        for _ in 0..<200 where engine.backupBusy() {
            Thread.sleep(forTimeInterval: 0.02)
            if engine.accept(samples: [Float](repeating: 0, count: 320), rate: 16_000) { return true }
        }
        return false
    }

    private var models: String {
        get throws { try XCTUnwrap(Bundle.main.resourceURL?.appendingPathComponent("wake").path) }
    }

    func testCorpusNeverFalseAcceptsAndTheSpotterWakes() throws {
        let engine = try WakeEngine.spotterOnly(models: try models, name: "Ava", nameOnly: false)
        XCTAssertEqual(engine.backupState(), .off)
        let woke = try ["hey-ava.wav", "hey-ava-uk.wav", "hey-ava-us.wav"].filter { try detects(engine, $0, 0.35) }
        print("iOS spotter-only recall at 0.35: \(woke)")
        XCTAssertFalse(woke.isEmpty)
        for clip in ["ava.wav", "negative.wav"] {
            for gain: Float in [0.05, 0.35, 0.8] {
                XCTAssertFalse(try detects(engine, clip, gain), "\(clip)@\(gain)")
            }
        }
    }

    /// The full desktop detector (spotter plus the embedded Whisper backup).
    func testTheFullDetectorWakesOnQuietSpeechAndNeverFalseAccepts() throws {
        let engine = try WakeEngine(models: try models, name: "Ava", nameOnly: false)
        let loading = Date()
        while engine.backupState() == .loading, Date().timeIntervalSince(loading) < 60 {
            _ = engine.accept(samples: [], rate: 16_000)
            Thread.sleep(forTimeInterval: 0.02)
        }
        XCTAssertEqual(engine.backupState(), .ready, engine.backupError() ?? "")
        print("iOS backup ready after \(Date().timeIntervalSince(loading)) s")
        for gain: Float in [0.35, 0.05] {
            for clip in ["hey-ava.wav", "hey-ava-uk.wav", "hey-ava-us.wav"] {
                XCTAssertTrue(try detects(engine, clip, gain), "\(clip)@\(gain)")
            }
        }
        for clip in ["ava.wav", "negative.wav"] {
            for gain: Float in [0.05, 0.35, 0.8] {
                XCTAssertFalse(try detects(engine, clip, gain), "\(clip)@\(gain)")
            }
        }
        let stats = engine.backupStats()
        print("iOS backup stats: \(stats)")
        XCTAssertEqual(stats.failures, 0)
        XCTAssertGreaterThan(stats.decodes, 0)
    }
}

/// Keychain persistence with a disposable service name; removed afterwards.
final class IdentityStoreTests: XCTestCase {
    func testIdentityAndRecordSurviveAndClear() throws {
        let store = IdentityStore(service: "dev.notdot.mobile.test.\(UUID().uuidString)")
        defer { try? store.clear() }
        XCTAssertNil(try store.identity())
        let identity = try store.identityCreatingIfNeeded()
        XCTAssertEqual(identity.count, 32)
        XCTAssertEqual(try store.identityCreatingIfNeeded(), identity, "created once")
        try store.savePairedRecord("notdot-paired:1:e30")
        XCTAssertEqual(try store.pairedRecord(), "notdot-paired:1:e30")
        // A new store value (as after an app restart) reads the same items.
        let restarted = IdentityStore(service: store.service)
        XCTAssertEqual(try restarted.identity(), identity)
        _ = try PhoneLink.restore(identity: identity, paired: nil)
        try restarted.clear()
        XCTAssertNil(try store.identity())
        XCTAssertNil(try store.pairedRecord())
    }
}

/// Step-up adapter contract. Simulator only: the Simulator reports a Secure
/// Enclave but is not a phone's hardware, so this proves the adapter
/// refuses it explicitly and never substitutes a software key. Secure Enclave creation, Face ID prompts and signing with
/// the hardware key need a physical iPhone.
final class StepUpKeyStoreTests: XCTestCase {
    func testNoSecureEnclaveIsReportedNotDowngraded() throws {
        let store = StepUpKeyStore(tag: Data("dev.notdot.mobile.test.\(UUID().uuidString)".utf8))
        defer { try? store.delete() }
        #if targetEnvironment(simulator)
        XCTAssertFalse(StepUpKeyStore.hardwareAvailable)
        XCTAssertThrowsError(try store.publicKey()) { error in
            guard case StepUpKeyStore.Failure.noSecureHardware = error else { return XCTFail("\(error)") }
        }
        XCTAssertThrowsError(try store.publicKey(), "still nothing on a second try")
        #else
        throw XCTSkip("device run: covered by the manual Secure Enclave check in mobile/README.md")
        #endif
    }

    /// The adapter's key encoding and signature format, with a throwaway
    /// software key (not stored, never used by the app): the public key it
    /// exports is the 65-byte SEC1 point the core binds into App Attest.
    func testKeyAndSignatureFormatsMatchTheCore() throws {
        let attributes: [String: Any] = [kSecAttrKeyType as String: kSecAttrKeyTypeECSECPrimeRandom,
                                         kSecAttrKeySizeInBits as String: 256]
        var error: Unmanaged<CFError>?
        let key = try XCTUnwrap(SecKeyCreateRandomKey(attributes as CFDictionary, &error))
        let publicKey = try StepUpKeyStore.publicKey(of: key)
        XCTAssertEqual(publicKey.count, 65)
        XCTAssertEqual(publicKey.first, 0x04)
        let request = AttestRequest(androidChallenge: Data(count: 32), desktop: Data(repeating: 1, count: 32),
                                    phone: Data(repeating: 2, count: 32), nonce: Data(repeating: 3, count: 32))
        XCTAssertEqual(try appAttestClientDataHash(request: request, stepUpKey: publicKey).count, 32)
        let signature = try StepUpKeyStore.sign(Data("synthetic".utf8), with: key)
        XCTAssertEqual(signature.first, 0x30, "DER sequence")
        XCTAssertTrue(SecKeyVerifySignature(SecKeyCopyPublicKey(key)!, .ecdsaSignatureMessageX962SHA256,
                                            Data("synthetic".utf8) as CFData, signature as CFData, &error))
    }
}

/// Pairs with a desktop simulator on the host (see mobile/README.md). Skipped
/// unless the runner passes TEST_RUNNER_NOTDOT_TEST_QR_FILE.
final class LinkEndToEndTests: XCTestCase {
    func testPairDirectThenRelayOnlyRetryCommitsOnce() async throws {
        guard let path = ProcessInfo.processInfo.environment["NOTDOT_TEST_QR_FILE"] else {
            throw XCTSkip("no desktop simulator; set TEST_RUNNER_NOTDOT_TEST_QR_FILE")
        }
        let qr = try String(contentsOfFile: path, encoding: .utf8)
        let link = PhoneLink()
        let code = try await link.pair(qr: qr, name: "Simulator phone")
        XCTAssertEqual(code.count, 7)
        guard case .approved = try await link.awaitApproval() else { return XCTFail("not approved") }
        let direct = try await link.connect(relayOnly: false)
        XCTAssertEqual(direct, .direct)
        let id = newRequestId()
        let first = try await link.addNote(requestId: id, text: "Synthetic note")
        let relayed = try await link.connect(relayOnly: true)
        XCTAssertEqual(relayed, .relay)
        let retried = try await link.addNote(requestId: id, text: "Synthetic note")
        XCTAssertEqual(first, retried, "the retry returns the recorded outcome")
        let notes = try await link.listNotes()
        XCTAssertEqual(notes.filter { $0 == "Synthetic note" }.count, 1)

        // The real refusal path on the Simulator: no Secure Enclave and no
        // App Attest, so setting up fails here, before anything is sent,
        // and the real desktop has no key for this phone.
        let status = try await link.stepUpStatus()
        XCTAssertFalse(status.enrolled)
        do {
            _ = try await link.setUpStepUp(attester: AppleAttester())
            XCTFail("the Simulator must not set up step-up")
        } catch MobileError.Unavailable {}
        let after = try await link.stepUpStatus()
        XCTAssertFalse(after.enrolled)
        do {
            _ = try await link.resetMemory(requestId: newRequestId(), signer: AppleSigner(reason: "test"))
            XCTFail("no key, no action")
        } catch MobileError.Unavailable {}
    }
}

/// The sensitive-actions screen model against the debug-only scripted
/// backend (test adapter; never genuine hardware evidence).
@MainActor
final class SensitiveActionsModelTests: XCTestCase {
    private func model(_ scenario: String) -> (SensitiveActionsModel, ScriptedSensitiveActions, () -> String?) {
        let backend = ScriptedSensitiveActions(scenario: scenario)
        var unpaired: String?
        let model = SensitiveActionsModel(backend: backend) { unpaired = $0 }
        return (model, backend, { unpaired })
    }

    func testSetUpThenEraseOnceAndOutcomesInPlainWords() async {
        let (model, backend, _) = model("setup")
        await model.refresh()
        XCTAssertFalse(model.canAct)
        XCTAssertTrue(model.statusText.hasPrefix("Not set up"))
        await model.setUp()
        XCTAssertEqual(model.outcome, .done("Set up. \(describeProtection(protection: .appleAppAttested))"))
        XCTAssertTrue(model.canAct)
        XCTAssertTrue(model.statusText.contains("test key, not real hardware"))
        // Two taps at once: one request, one effect.
        async let first: Void = model.eraseMemories()
        async let second: Void = model.eraseMemories()
        _ = await (first, second)
        let effects = await backend.effects
        XCTAssertEqual(effects, 1)
        XCTAssertEqual(model.outcome, .done("Erased 3 memories."))
        XCTAssertNil(model.pendingResetId)
    }

    func testEveryRefusalIsReportedAndNothingIsRetriedSilently() async {
        let cases: [(String, (SensitiveOutcome?) -> Bool)] = [
            ("cancelled", { $0 == .cancelled }),
            ("denied", { if case .denied = $0 { true } else { false } }),
            ("expired", { $0 == .expired }),
            ("offline", { if case .offline = $0 { true } else { false } }),
            ("unavailable", { if case .unavailable = $0 { true } else { false } }),
        ]
        for (scenario, expected) in cases {
            let (model, backend, _) = model(scenario)
            await model.refresh()
            if scenario == "unavailable" {
                await model.setUp()
            } else {
                await model.eraseMemories()
            }
            XCTAssertTrue(expected(model.outcome), "\(scenario): \(String(describing: model.outcome))")
            XCTAssertTrue(model.outcome?.isProblem ?? false)
            XCTAssertFalse(model.busy)
            let effects = await backend.effects
            XCTAssertEqual(effects, 0, scenario)
            // Only a dropped connection keeps the request id for a retry.
            XCTAssertEqual(model.pendingResetId != nil, scenario == "offline", scenario)
        }
    }

    func testRevokedForgetsThePairing() async {
        let (model, _, unpaired) = model("revoked")
        await model.refresh()
        await model.eraseMemories()
        guard case .revoked = model.outcome else { return XCTFail("\(String(describing: model.outcome))") }
        XCTAssertNotNil(unpaired())
        XCTAssertNil(model.status)
        XCTAssertFalse(model.canAct)
    }

    func testNotGrantedCannotAct() async {
        let (model, _, _) = model("notgranted")
        await model.refresh()
        XCTAssertFalse(model.canAct)
        XCTAssertTrue(model.statusText.contains("Allow sensitive actions"))
    }

    func testTheRealAttesterRefusesTheSimulator() throws {
        #if targetEnvironment(simulator)
        let request = AttestRequest(androidChallenge: Data(count: 32), desktop: Data(count: 32),
                                    phone: Data(count: 32), nonce: Data(count: 32))
        XCTAssertFalse(AppAttest.supported)
        XCTAssertThrowsError(try AppleAttester().attest(request: request)) { error in
            guard case MobileError.Unavailable = error else { return XCTFail("\(error)") }
        }
        XCTAssertThrowsError(try AppAttest.standard.assertion(clientDataHash: Data(count: 32)))
        #else
        throw XCTSkip("device run: App Attest needs an enrolled team's entitlement")
        #endif
    }
}
